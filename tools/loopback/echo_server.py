#!/usr/bin/env python3
"""Loopback backends for the NativeCore protocol loopback tests.

One process, five sockets (all 127.0.0.1):

  TCP 18080  echo        — every byte received is sent back verbatim.
  UDP 18081  echo        — every datagram is sent back verbatim.
  TCP 18082  blackhole   — accepts connections and reads NOTHING while paused,
                           so a sender's flow control is the only thing that
                           can stop it; used by the back-pressure tests.
  UDP 18083  control     — datagram "go"    : blackhole starts discarding
                                              (reads and drops) on every held
                                              connection and on future ones.
                           datagram "pause" : future blackhole connections are
                                              held unread again.
  UDP 18084  dns         — a minimal DNS server: every query gets one A answer
                           192.0.2.53 (TTL 60) for its first question
                           (feat/nc-sudoku-udp: DNS over UDP through a tunnel).
  TCP 18020  socks5      — minimal SOCKS5 (no-auth / fixed user+pass), CONNECT.
  TCP 18019  socks5-tls  — the same SOCKS5 server behind TLS (cert from
                           $NC_LOOPBACK_DIR, generated by start-servers.sh).

The sing-box inbounds route to whatever target the client names, so the
tests pick echo vs blackhole purely by the target port they ask for.

Stdlib only, so this runs on any macOS/Linux python3. SIGTERM/SIGINT stops it.
"""

import os
import socket
import ssl
import sys
import threading

HOST = "127.0.0.1"
TCP_ECHO_PORT = 18080
UDP_ECHO_PORT = 18081
BLACKHOLE_PORT = 18082
CONTROL_PORT = 18083
DNS_PORT = 18084
DNS_ANSWER = bytes([192, 0, 2, 53])
# feat/nc-socks5-tls (#168): minimal SOCKS5 servers for the SOCKS5-over-TLS
# loopback tests — plain on :18020, TLS-wrapped on :18019 (cert generated by
# start-servers.sh into $NC_LOOPBACK_DIR, SAN localhost / 127.0.0.1).
SOCKS5_TLS_PORT = 18019
SOCKS5_PORT = 18020
SOCKS5_USER = b"nc-loop-socks-user"
SOCKS5_PASS = b"nc-loop-socks-pw"

_state_lock = threading.Lock()
_discarding = False          # blackhole mode: False = hold unread, True = read & drop
_held = []                   # blackhole connections waiting for "go"


def _discard_loop(conn: socket.socket) -> None:
    try:
        while True:
            data = conn.recv(65536)
            if not data:
                break
    except OSError:
        pass
    finally:
        try:
            conn.close()
        except OSError:
            pass


def _start_discarding(conn: socket.socket) -> None:
    threading.Thread(target=_discard_loop, args=(conn,), daemon=True).start()


def _set_discarding(on: bool) -> None:
    global _discarding
    with _state_lock:
        _discarding = on
        held, _held[:] = list(_held), []
    if on:
        for conn in held:
            _start_discarding(conn)


def tcp_echo_server() -> None:
    srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    srv.bind((HOST, TCP_ECHO_PORT))
    srv.listen(64)

    def handle(conn: socket.socket) -> None:
        try:
            while True:
                data = conn.recv(65536)
                if not data:
                    break
                conn.sendall(data)
        except OSError:
            pass
        finally:
            conn.close()

    while True:
        conn, _ = srv.accept()
        threading.Thread(target=handle, args=(conn,), daemon=True).start()


def blackhole_server() -> None:
    srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    srv.bind((HOST, BLACKHOLE_PORT))
    srv.listen(64)
    while True:
        conn, _ = srv.accept()
        with _state_lock:
            if _discarding:
                _start_discarding(conn)
            else:
                _held.append(conn)


def udp_echo_server() -> None:
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.bind((HOST, UDP_ECHO_PORT))
    while True:
        data, addr = sock.recvfrom(65535)
        sock.sendto(data, addr)


def control_server() -> None:
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.bind((HOST, CONTROL_PORT))
    while True:
        data, _ = sock.recvfrom(1024)
        cmd = data.strip().lower()
        if cmd == b"go":
            _set_discarding(True)
        elif cmd == b"pause":
            _set_discarding(False)


def dns_answer(query: bytes):
    """One A answer for the query's first question; None for anything that is not a parseable query."""
    if len(query) < 12 or query[2] & 0x80:
        return None
    i = 12
    while i < len(query) and query[i] != 0:
        if query[i] & 0xC0:
            return None
        i += 1 + query[i]
    if i + 5 > len(query):
        return None
    question = query[12:i + 5]
    header = query[0:2] + bytes([0x81, 0x80]) + b"\x00\x01\x00\x01\x00\x00\x00\x00"
    answer = b"\xc0\x0c" + b"\x00\x01\x00\x01" + (60).to_bytes(4, "big") + b"\x00\x04" + DNS_ANSWER
    return header + question + answer


def dns_server() -> None:
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    sock.bind((HOST, DNS_PORT))
    while True:
        data, addr = sock.recvfrom(4096)
        reply = dns_answer(data)
        if reply is not None:
            sock.sendto(reply, addr)


def _recv_exact(conn: socket.socket, n: int) -> bytes:
    buf = b""
    while len(buf) < n:
        chunk = conn.recv(n - len(buf))
        if not chunk:
            raise ConnectionError("eof")
        buf += chunk
    return buf


def _pump(src: socket.socket, dst: socket.socket) -> None:
    try:
        while True:
            data = src.recv(65536)
            if not data:
                break
            dst.sendall(data)
    except OSError:
        pass
    finally:
        try:
            dst.shutdown(socket.SHUT_WR)
        except OSError:
            pass


def _socks5_handle(conn: socket.socket) -> None:
    """Minimal SOCKS5: no-auth or user/pass (fixed loopback creds), CONNECT only."""
    try:
        head = _recv_exact(conn, 2)
        if head[0] != 0x05:
            return
        methods = _recv_exact(conn, head[1])
        if 0x02 in methods:
            conn.sendall(b"\x05\x02")
            auth = _recv_exact(conn, 2)
            if auth[0] != 0x01:
                return
            user = _recv_exact(conn, auth[1])
            plen = _recv_exact(conn, 1)[0]
            pw = _recv_exact(conn, plen)
            if user != SOCKS5_USER or pw != SOCKS5_PASS:
                conn.sendall(b"\x01\x01")
                return
            conn.sendall(b"\x01\x00")
        elif 0x00 in methods:
            conn.sendall(b"\x05\x00")
        else:
            conn.sendall(b"\x05\xff")
            return
        req = _recv_exact(conn, 4)
        if req[0] != 0x05:
            return
        if req[1] != 0x01:  # CONNECT only
            conn.sendall(b"\x05\x07\x00\x01\x00\x00\x00\x00\x00\x00")
            return
        atyp = req[3]
        if atyp == 0x01:
            host = socket.inet_ntoa(_recv_exact(conn, 4))
        elif atyp == 0x03:
            dlen = _recv_exact(conn, 1)[0]
            host = _recv_exact(conn, dlen).decode("utf-8", "replace")
        elif atyp == 0x04:
            host = socket.inet_ntop(socket.AF_INET6, _recv_exact(conn, 16))
        else:
            conn.sendall(b"\x05\x08\x00\x01\x00\x00\x00\x00\x00\x00")
            return
        port = int.from_bytes(_recv_exact(conn, 2), "big")
        try:
            upstream = socket.create_connection((host, port), timeout=10)
        except OSError:
            conn.sendall(b"\x05\x05\x00\x01\x00\x00\x00\x00\x00\x00")
            return
        conn.sendall(b"\x05\x00\x00\x01\x7f\x00\x00\x01" + SOCKS5_PORT.to_bytes(2, "big"))
        threading.Thread(target=_pump, args=(conn, upstream), daemon=True).start()
        _pump(upstream, conn)
        upstream.close()
    except (OSError, ConnectionError):
        pass
    finally:
        try:
            conn.close()
        except OSError:
            pass


def _serve(port: int, wrap) -> None:
    srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
    srv.bind((HOST, port))
    srv.listen(64)
    while True:
        conn, _ = srv.accept()
        if wrap is not None:
            try:
                conn = wrap(conn)
            except (ssl.SSLError, OSError):
                conn.close()
                continue
        threading.Thread(target=_socks5_handle, args=(conn,), daemon=True).start()


def socks5_server() -> None:
    _serve(SOCKS5_PORT, None)


def socks5_tls_server() -> None:
    run_dir = os.environ.get("NC_LOOPBACK_DIR", "/tmp/nc-loopback")
    cert = os.path.join(run_dir, "cert.pem")
    key = os.path.join(run_dir, "key.pem")
    if not (os.path.exists(cert) and os.path.exists(key)):
        print(f"echo_server: socks5-tls disabled (no cert in {run_dir})", flush=True)
        return
    ctx = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    ctx.load_cert_chain(cert, key)
    _serve(SOCKS5_TLS_PORT, lambda c: ctx.wrap_socket(c, server_side=True))


def main() -> int:
    for fn in (tcp_echo_server, blackhole_server, udp_echo_server, control_server, dns_server,
               socks5_server, socks5_tls_server):
        threading.Thread(target=fn, daemon=True).start()
    print(
        f"echo_server: tcp-echo :{TCP_ECHO_PORT} udp-echo :{UDP_ECHO_PORT} "
        f"blackhole :{BLACKHOLE_PORT} control :{CONTROL_PORT} dns :{DNS_PORT} "
        f"socks5 :{SOCKS5_PORT} socks5-tls :{SOCKS5_TLS_PORT}",
        flush=True,
    )
    try:
        threading.Event().wait()
    except KeyboardInterrupt:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
