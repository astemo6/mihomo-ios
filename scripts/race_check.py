#!/usr/bin/env python3
"""test/selftest: classify `go test -race` reports.

mihomo itself is not race-clean while a config is re-applied with traffic in flight (dialer / resolver /
inbound globals written by ApplyConfig), and the bridge tests do exactly that. Those reports are listed as
upstream; any race whose racing access (either side) has its first non-library frame in this repository's
non-test code fails the check.

usage: race_check.py go-test-race.log [--summary FILE]
"""
import re
import sys

OURS = "github.com/astemo6/mihomo-ios/"
SKIP = ("runtime.", "reflect.", "encoding/json.", "internal/", "sync.", "sync/atomic.", "go.yaml.in/", "fmt.",
        "strings.", "bytes.", "sort.", "time.", "os.", "io.", "bufio.", "net.", "syscall.")


def top_frame(lines):
    """First frame of an access stack that is not standard library / generic decoding."""
    for i, l in enumerate(lines):
        s = l.strip()
        if not s or s.startswith("/") or s.startswith("<autogenerated>"):
            continue
        if s.startswith(SKIP):
            continue
        f = lines[i + 1].strip() if i + 1 < len(lines) else ""
        return s, f
    return "", ""


def main():
    path = sys.argv[1]
    summary = sys.argv[sys.argv.index("--summary") + 1] if "--summary" in sys.argv else None
    text = open(path, encoding="utf-8", errors="replace").read()
    text = re.sub(r"^\S+ \S+ [^\n]*?\(UTC[^)]*\) ", "", text, flags=re.M)  # runner timestamps, if any
    blocks = text.split("WARNING: DATA RACE")[1:]
    ours, upstream, tests = {}, {}, {}
    for b in blocks:
        body = b.split("==================")[0]
        parts = re.split(r"\n(?=(?:Previous )?(?:[Rr]ead|[Ww]rite) at 0x)", body)
        accesses = []
        for p in parts:
            if re.match(r"\s*(?:Previous )?(?:[Rr]ead|[Ww]rite) at", p):
                stack = p.split("\nGoroutine ")[0].split("\n")[1:]
                accesses.append(top_frame(stack))
        key = " ⟷ ".join(sorted(f"{fn} @ {loc.split(' ')[0].split('/')[-1]}" for fn, loc in accesses))
        if any(OURS in fn and "_test.go" not in loc for fn, loc in accesses):
            ours[key] = ours.get(key, 0) + 1
        elif any(OURS in fn for fn, _ in accesses):
            tests[key] = tests.get(key, 0) + 1
        else:
            upstream[key] = upstream.get(key, 0) + 1
    out = [f"race reports: {len(blocks)} (ours {sum(ours.values())}, test-only {sum(tests.values())}, upstream {sum(upstream.values())})"]
    for title, d in (("OURS (fail)", ours), ("test code", tests), ("upstream mihomo", upstream)):
        if d:
            out.append(f"## {title}")
            out += [f"- {n}× {k}" for k, n in sorted(d.items(), key=lambda kv: -kv[1])]
    print("\n".join(out))
    if summary:
        with open(summary, "a", encoding="utf-8") as f:
            f.write("### go test -race\n" + "\n".join(out) + "\n")
    sys.exit(1 if ours or tests else 0)


if __name__ == "__main__":
    main()
