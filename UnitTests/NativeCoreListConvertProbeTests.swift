    func testFMZListConversionKeepsDomainRules() {
        let data = Data(Self.listText.utf8)
        let (text, ok, skipped) = NCProviderPorts.convertListText(data, kind: "list")
        let lines = text.split(separator: "\n")
        func count(_ prefix: String) -> Int { lines.filter { $0.hasPrefix(prefix) }.count }
        print("PROBE4 converted ok=\(ok) skipped=\(skipped) total=\(lines.count) DOMAIN=\(count("DOMAIN,")) DOMAIN-SUFFIX=\(count("DOMAIN-SUFFIX,")) DOMAIN-KEYWORD=\(count("DOMAIN-KEYWORD,")) IP-CIDR=\(count("IP-CIDR"))")
        for probe in ["DOMAIN,afd.baidu.com", "DOMAIN,als.baidu.com", "DOMAIN,nsclick.baidu.com", "DOMAIN,mobads.baidu.com"] {
            XCTAssertTrue(text.contains(probe), "converted list must contain \(probe)")
        }
        XCTAssertGreaterThan(count("DOMAIN-SUFFIX,"), 100, "host-suffix lines must survive as DOMAIN-SUFFIX")
        XCTAssertGreaterThan(ok, 300, "most subset lines must convert (ok=\(ok), skipped=\(skipped))")
    }
