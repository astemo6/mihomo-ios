import Foundation

/// Raw AES block cipher (FIPS-197), encrypt and decrypt of single 16-byte
/// blocks with 128/192/256-bit keys. Only VMess's authID needs ECB; bulk data
/// goes through CryptoKit AES-GCM. S-boxes were generated from the GF(2^8)
/// definition and are covered by the FIPS-197 test vectors.
struct NCAES {
    private let roundKeys: [[UInt8]]
    private let rounds: Int

    init?(key: Data) {
        let nk: Int
        switch key.count {
        case 16: nk = 4
        case 24: nk = 6
        case 32: nk = 8
        default: return nil
        }
        rounds = nk + 6
        let rcon: [UInt8] = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]
        var w = [UInt8](key)
        var generated = key.count
        var r = 0
        while generated < 16 * (rounds + 1) {
            var temp = Array(w[(generated - 4)..<generated])
            if generated % key.count == 0 {
                temp = [Self.sBox[Int(temp[1])] ^ rcon[r], Self.sBox[Int(temp[2])], Self.sBox[Int(temp[3])], Self.sBox[Int(temp[0])]]
                r += 1
            } else if nk > 6 && generated % key.count == 16 {
                temp = temp.map { Self.sBox[Int($0)] }
            }
            for t in temp {
                w.append(w[generated - key.count] ^ t)
                generated += 1
            }
        }
        roundKeys = (0...rounds).map { Array(w[($0 * 16)..<($0 * 16 + 16)]) }
    }

    func encryptBlock(_ block: Data) -> Data {
        precondition(block.count == 16)
        var state = [UInt8](block)
        addRoundKey(&state, roundKeys[0])
        for round in 1..<rounds {
            subBytes(&state)
            shiftRows(&state)
            mixColumns(&state)
            addRoundKey(&state, roundKeys[round])
        }
        subBytes(&state)
        shiftRows(&state)
        addRoundKey(&state, roundKeys[rounds])
        return Data(state)
    }

    func decryptBlock(_ block: Data) -> Data {
        precondition(block.count == 16)
        var state = [UInt8](block)
        addRoundKey(&state, roundKeys[rounds])
        for round in stride(from: rounds - 1, through: 1, by: -1) {
            invShiftRows(&state)
            invSubBytes(&state)
            addRoundKey(&state, roundKeys[round])
            invMixColumns(&state)
        }
        invShiftRows(&state)
        invSubBytes(&state)
        addRoundKey(&state, roundKeys[0])
        return Data(state)
    }

    // State is column-major: state[row + 4*col], matching the key schedule.

    private func addRoundKey(_ state: inout [UInt8], _ key: [UInt8]) {
        for i in 0..<16 { state[i] ^= key[i] }
    }

    private func subBytes(_ state: inout [UInt8]) {
        for i in 0..<16 { state[i] = Self.sBox[Int(state[i])] }
    }

    private func invSubBytes(_ state: inout [UInt8]) {
        for i in 0..<16 { state[i] = Self.invSBox[Int(state[i])] }
    }

    private func shiftRows(_ state: inout [UInt8]) {
        var t: UInt8
        t = state[1]; state[1] = state[5]; state[5] = state[9]; state[9] = state[13]; state[13] = t
        t = state[2]; state[2] = state[10]; state[10] = t
        t = state[6]; state[6] = state[14]; state[14] = t
        t = state[15]; state[15] = state[11]; state[11] = state[7]; state[7] = state[3]; state[3] = t
    }

    private func invShiftRows(_ state: inout [UInt8]) {
        var t: UInt8
        t = state[13]; state[13] = state[9]; state[9] = state[5]; state[5] = state[1]; state[1] = t
        t = state[2]; state[2] = state[10]; state[10] = t
        t = state[6]; state[6] = state[14]; state[14] = t
        t = state[3]; state[3] = state[7]; state[7] = state[11]; state[11] = state[15]; state[15] = t
    }

    private static func mul(_ a: UInt8, _ b: UInt8) -> UInt8 {
        var (x, y, p): (UInt8, UInt8, UInt8) = (a, b, 0)
        for _ in 0..<8 {
            if y & 1 != 0 { p ^= x }
            let hi = x & 0x80
            x <<= 1
            if hi != 0 { x ^= 0x1b }
            y >>= 1
        }
        return p
    }

    private func mixColumns(_ state: inout [UInt8]) {
        for c in 0..<4 {
            let i = c * 4
            let (a, b, cc, d) = (state[i], state[i + 1], state[i + 2], state[i + 3])
            state[i] = Self.mul(a, 2) ^ Self.mul(b, 3) ^ cc ^ d
            state[i + 1] = a ^ Self.mul(b, 2) ^ Self.mul(cc, 3) ^ d
            state[i + 2] = a ^ b ^ Self.mul(cc, 2) ^ Self.mul(d, 3)
            state[i + 3] = Self.mul(a, 3) ^ b ^ cc ^ Self.mul(d, 2)
        }
    }

    private func invMixColumns(_ state: inout [UInt8]) {
        for c in 0..<4 {
            let i = c * 4
            let (a, b, cc, d) = (state[i], state[i + 1], state[i + 2], state[i + 3])
            state[i] = Self.mul(a, 14) ^ Self.mul(b, 11) ^ Self.mul(cc, 13) ^ Self.mul(d, 9)
            state[i + 1] = Self.mul(a, 9) ^ Self.mul(b, 14) ^ Self.mul(cc, 11) ^ Self.mul(d, 13)
            state[i + 2] = Self.mul(a, 13) ^ Self.mul(b, 9) ^ Self.mul(cc, 14) ^ Self.mul(d, 11)
            state[i + 3] = Self.mul(a, 11) ^ Self.mul(b, 13) ^ Self.mul(cc, 9) ^ Self.mul(d, 14)
        }
    }

